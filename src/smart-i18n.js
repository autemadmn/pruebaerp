let locale = 'es';

export function setSmartLocale(next) {
  locale = STRINGS[next] ? next : 'es';
}

export function getSmartLocale() {
  return locale;
}

/** t('cart.title') con sustitución de {variables}. */
export function t(key, vars) {
  const table = STRINGS[locale] || STRINGS.es;
  let value = table[key] ?? STRINGS.es[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, replacement]) => {
      value = value.split(`{${name}}`).join(String(replacement));
    });
  }
  return value;
}

/** Plural sencillo: t2('cart.items', n). */
export function tp(key, count, vars) {
  return t(`${key}.${count === 1 ? 'one' : 'other'}`, { n: count, ...vars });
}

